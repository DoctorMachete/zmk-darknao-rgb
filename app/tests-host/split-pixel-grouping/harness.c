/* ---- fake k_msgq ---------------------------------------------------------------------- */
#define QCAP 512
struct fake_msgq {
    struct central_cmd_wrapper items[QCAP];
    int head, tail;
};
static struct fake_msgq zmk_split_central_split_run_msgq;

static int k_msgq_get(struct fake_msgq *q, void *out, int timeout) {
    (void)timeout;
    if (q->head == q->tail) {
        return -ENOMSG;
    }
    memcpy(out, &q->items[q->head++], sizeof(struct central_cmd_wrapper));
    return 0;
}
static void q_put(struct central_cmd_wrapper w) {
    assert(zmk_split_central_split_run_msgq.tail < QCAP);
    zmk_split_central_split_run_msgq.items[zmk_split_central_split_run_msgq.tail++] = w;
}
static void q_reset(void) { memset(&zmk_split_central_split_run_msgq, 0, sizeof(zmk_split_central_split_run_msgq)); }

